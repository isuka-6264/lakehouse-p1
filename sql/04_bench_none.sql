DROP TABLE IF EXISTS bronze.bench_none.nation;
DROP TABLE IF EXISTS bronze.bench_none.customer;
DROP TABLE IF EXISTS bronze.bench_none.orders;
DROP TABLE IF EXISTS bronze.bench_none.lineitem;
