CREATE TABLE bronze.bench_none.orders   WITH (format = 'PARQUET') AS SELECT * FROM tpch.sf1.orders;
CREATE TABLE bronze.bench_none.lineitem WITH (format = 'PARQUET') AS SELECT * FROM tpch.sf1.lineitem;
